/** วันนี้ตามเวลาท้องถิ่น (YYYY-MM-DD) — ไม่ใช้ UTC */
export const todayLocal = () => {
  const d = new Date();
  return new Date(d.getTime() - d.getTimezoneOffset() * 60000)
    .toISOString()
    .slice(0, 10);
};
